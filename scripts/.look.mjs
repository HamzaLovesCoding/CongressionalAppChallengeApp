import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM, args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const base = 'http://127.0.0.1:4173/';
await page.goto(base + '#/feed/school-bus', { waitUntil: 'load' }); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/1-text-lesson.png` });
await page.locator('.is-current [data-post-choice="0"]').click(); await page.waitForTimeout(200);
await page.locator('.is-current [data-post-choice="1"]').click(); await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/2-text-lesson-progress.png` });
await page.locator('.is-current [data-post-choice="0"]').click(); await page.waitForTimeout(200);
await page.locator('.is-current [data-post-choice="1"]').click(); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/3-text-lesson-check.png` });
await page.goto(base + '#/feed/lane-end-scan', { waitUntil: 'load' }); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/4-video-sound.png` });
await page.goto(base + '#/home', { waitUntil: 'load' }); await page.waitForTimeout(700);
await page.click('[data-menu]'); await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/6-menu.png` });
console.log('errors', errors);
await browser.close();
