import { chromium } from 'playwright';
const out = process.argv[2];
const base = 'http://127.0.0.1:5173/';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM, args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
const log = (...a) => console.log(...a);
let n = 0; const shot = name => page.screenshot({ path: `${out}/${String(++n).padStart(2, '0')}-${name}.png` });
const st = () => page.evaluate(() => ({ hash: location.hash, sheet: document.querySelector('.lane-sheet')?.getAttribute('aria-hidden'), timer: document.querySelector('.is-current .lane-scroll-time time')?.textContent, label: document.querySelector('.lane-sheet[aria-hidden="false"] .lane-round-label')?.textContent?.replace(/\s+/g, ' '), title: document.querySelector('.lane-sheet[aria-hidden="false"] .lane-question')?.textContent }));
const swipe = () => page.evaluate(() => { const f = document.querySelector('.lane-feed'); const cur = document.querySelector('.is-current'); f.scrollTo({ top: cur.offsetTop + cur.offsetHeight }); });
const watchToEnd = () => page.evaluate(async () => { const v = document.querySelector('.is-current video'); await new Promise(r => v.readyState >= 1 ? r() : v.addEventListener('loadedmetadata', r, { once: true })); v.currentTime = Math.max(0, v.duration - 0.6); await v.play().catch(() => {}); });
const { CLIPS } = await import(process.cwd() + '/src/feed/clips.ts');
const clip = id => CLIPS.find(c => c.id === id);

await page.goto(base + '#/home', { waitUntil: 'load' }); await page.waitForTimeout(800);
log('HOME:', (await page.textContent('.home-sign-face')).replace(/\s+/g, ' ').trim());
await page.click('.home-sign-face'); await page.waitForTimeout(3500);
log('L1 playing', await st()); await shot('lesson1-playing');
await swipe(); await page.waitForTimeout(1200);
log('swipe early from L1', await st()); await shot('are-you-sure');
await page.click('.lane-sheet [data-gate-stay]'); await page.waitForTimeout(1500);
log('keep watching', await st());
await swipe(); await page.waitForTimeout(1200);
await page.click('.lane-sheet [data-gate-later]'); await page.waitForTimeout(1500);
log('after review later', await st()); await shot('lesson2-after-review-later');
await watchToEnd(); await page.waitForTimeout(2500);
log('L2 ended', await st()); await shot('lesson2-quiz');
await page.click(`.lane-sheet [data-answer="${clip('after-collision').answer}"]`); await page.waitForTimeout(300); await shot('lesson2-correct');
await page.click('.lane-sheet [data-continue]'); await page.waitForTimeout(500);
log('after finish', await st()); await shot('lesson2-after-finish');
if (await page.isVisible('.lane-sheet [data-recall-show]')) { log('REINFORCE recall shown'); await page.click('.lane-sheet [data-recall-show]'); await page.waitForTimeout(200); await page.click('.lane-sheet [data-recall-got]'); await page.waitForTimeout(400); }
log('complete:', (await page.textContent('.lane-sheet-content')).replace(/\s+/g, ' ').slice(0, 300)); await shot('lesson2-complete');
await page.click('.lane-sheet [data-next]'); await page.waitForTimeout(1500);
log('next item', await st()); await shot('lesson3');
await watchToEnd(); await page.waitForTimeout(2500);
log('L3 ended (low stakes)', await st()); await shot('lesson3-flashcard');
await page.click('.lane-sheet [data-recall-show]'); await page.waitForTimeout(300); await shot('lesson3-flashcard-back');
await page.click('.lane-sheet [data-recall-got]'); await page.waitForTimeout(500); await shot('lesson3-complete');
log('L3 complete:', (await page.textContent('.lane-sheet-content')).replace(/\s+/g, ' ').slice(0, 200));
await page.goto(base + '#/home', { waitUntil: 'load' }); await page.waitForTimeout(900);
log('HOME after:', (await page.textContent('.home-sign-face')).replace(/\s+/g, ' ').trim());
log('HOME review row:', await page.textContent('.home-review-row').catch(() => 'none'));
log('HOME count:', await page.textContent('[data-completed]'));
await shot('home-after');
await page.click('nav a[href="#/feed"]'); await page.waitForTimeout(1500);
log('FEED TAB opens', await st()); await shot('feed-tab');
await page.goto(base + '#/progress', { waitUntil: 'load' }); await page.waitForTimeout(900);
log('PROGRESS:', (await page.textContent('.path-dashboard')).replace(/\s+/g, ' ').trim()); await shot('progress');
await page.goto(base + '#/review', { waitUntil: 'load' }); await page.waitForTimeout(1200);
log('REVIEW:', (await page.textContent('main')).replace(/\s+/g, ' ').slice(0, 600)); await shot('review');
log('ERRORS', errors);
await browser.close();
